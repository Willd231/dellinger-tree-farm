// Turns a Zoho Invoice "Items" CSV export into data/inventory.json for the
// "What We Grow" list. Prices are deliberately dropped: the site is quote-only.
//
// Usage:  node scripts/import-items.mjs path/to/Item.csv
//
// Keep the CSV out of git (it has prices). *.csv is in .gitignore.

import { readFileSync, writeFileSync } from "node:fs";

const BOTANICAL = {
  "Fraser Fir": "Abies fraseri",
  "Turkish Fir": "Abies bornmuelleriana",
  "Norway Spruce": "Picea abies",
  "White Pine": "Pinus strobus",
  "Eastern Hemlock": "Tsuga canadensis",
  "Mountain Laurel": "Kalmia latifolia",
  "Rosebay Rhododendron": "Rhododendron maximum",
};
const SHRUBS = new Set(["Mountain Laurel", "Rosebay Rhododendron"]);
const CATEGORY_ORDER = ["Evergreen Trees", "Flowering Shrubs", "Christmas Trees"];

// Minimal CSV parser (handles quoted fields with commas).
function parseCsv(text) {
  const rows = [];
  let row = [], field = "", q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') q = false;
      else field += c;
    } else if (c === '"') q = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field); rows.push(row); row = []; field = "";
    } else field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  const [head, ...body] = rows.filter((r) => r.some((v) => v.trim()));
  return body.map((r) => Object.fromEntries(head.map((h, i) => [h.trim(), (r[i] ?? "").trim()])));
}

// "Fraser Fir b&b, 4’-5’" -> { name, form, size, grade }
function parseName(raw) {
  const s = raw.replace(/[’‘]/g, "'");
  const m = s.match(/^(.*?)\s*(?:\((cut and bail?led)\)|\b(b&b)\b)\s*,\s*(\d+)'\s*-\s*(\d+)'/i);
  if (!m) return null;
  let name = m[1].trim();
  let grade = null;
  const g = name.match(/\s*#(\d+)$/);
  if (g) { grade = `#${g[1]} grade`; name = name.slice(0, g.index).trim(); }
  const form = m[2] ? "Cut & baled" : "B&B";
  return { name, form, size: `${m[4]}–${m[5]} ft`, grade };
}

const file = process.argv[2];
if (!file) { console.error("Usage: node scripts/import-items.mjs Item.csv"); process.exit(1); }

const skipped = [];
const items = [];
for (const r of parseCsv(readFileSync(file, "utf8"))) {
  if (r["Status"] !== "Active" || r["Product Type"] !== "goods") { skipped.push(`${r["Item Name"]} (${r["Status"]}, ${r["Product Type"]})`); continue; }
  const p = parseName(r["Item Name"]);
  if (!p) { skipped.push(`${r["Item Name"]} (couldn't read name/size)`); continue; }
  const category = p.form === "Cut & baled" ? "Christmas Trees" : SHRUBS.has(p.name) ? "Flowering Shrubs" : "Evergreen Trees";
  const notes = [p.grade, /limited/i.test(r["Description"]) ? "Limited quantity" : null].filter(Boolean);
  items.push({
    name: p.name,
    botanical: BOTANICAL[p.name] ?? null,
    category,
    size: p.size,
    form: p.form,
    ...(notes.length ? { note: notes.join(" · ") } : {}),
  });
}

const sizeKey = (s) => parseInt(s, 10);
items.sort((a, b) =>
  CATEGORY_ORDER.indexOf(a.category) - CATEGORY_ORDER.indexOf(b.category) ||
  a.name.localeCompare(b.name) ||
  sizeKey(a.size) - sizeKey(b.size) ||
  (a.note ?? "").localeCompare(b.note ?? ""));

const out = {
  _note: "Generated by scripts/import-items.mjs from a Zoho Items export. No prices on purpose. Edit by hand or re-run the script.",
  items,
};
writeFileSync("data/inventory.json", JSON.stringify(out, null, 2) + "\n");
console.log(`Wrote ${items.length} items to data/inventory.json`);
if (skipped.length) console.log("Skipped:\n  " + skipped.join("\n  "));
const missing = [...new Set(items.filter((i) => !i.botanical).map((i) => i.name))];
if (missing.length) console.log("No botanical name for (add to BOTANICAL):", missing.join(", "));
